"""sparrow-pico compiler: distil a full decider's answers on one robot's sensor schema into a
few-KB MLP per question, exported as a dependency-free C header.

A spec names the features (numbers, booleans, enums), optional plain-language rules, and the
questions. The compiler samples states, renders them as the decider reads them, has a teacher
label every (state, question), trains one small MLP per question on the raw feature vector, and
writes C plus a held-out report.

  # 1. sample + render rows for the teacher
  python training/pico_compile.py sample c/examples/specs/rover.json --n 4000 --work runs/pico-rover
  # 2. label them with a full Strands Decider (in an env with strands-decider installed)
  python training/label_decider.py CKPT runs/pico-rover/rows.jsonl runs/pico-rover/teacher.jsonl
  # 3. train + export
  python training/pico_compile.py build c/examples/specs/rover.json --work runs/pico-rover --out c/examples/esp32s3_robot/main
"""
from __future__ import annotations

import argparse
import json
import os
import random
import re

import numpy as np

NOUL = [["false", "the statement does not hold for this state"], ["true", "the statement holds for this state"]]


def options(q):
    if q["type"] == "noul":
        return NOUL
    if q["type"] == "choice":
        return [[k, v] for k, v in q["criteria"].items()]
    return [[str(i), v] for i, v in enumerate(q["criteria"])]


def sample_state(spec, rng):
    s = {}
    for f in spec["features"]:
        if f["type"] == "number":
            v = rng.uniform(f["min"], f["max"])
            s[f["name"]] = round(v, 2) if f["max"] - f["min"] <= 20 else round(v)
        elif f["type"] == "bool":
            s[f["name"]] = rng.random() < 0.5
        else:
            s[f["name"]] = rng.choice(f["values"])
    return s


def render(spec, s):
    lines = [f"rules: {spec['context']}"] if spec.get("context") else []
    for f in spec["features"]:
        v = s[f["name"]]
        if f["type"] == "bool":
            v = "yes" if v else "no"
        lines.append(f"{f['name']}: {v}{f.get('unit', '')}")
    return "\n".join(lines)


def featurize(spec, s):
    x = []
    for f in spec["features"]:
        v = s[f["name"]]
        if f["type"] == "number":
            x.append((v - f["min"]) / (f["max"] - f["min"]))
        elif f["type"] == "bool":
            x.append(1.0 if v else 0.0)
        else:
            x += [1.0 if v == e else 0.0 for e in f["values"]]
    return x


def cmd_sample(a):
    spec = json.load(open(a.spec))
    rng = random.Random(a.seed)
    os.makedirs(a.work, exist_ok=True)
    states = [sample_state(spec, rng) for _ in range(a.n)]
    json.dump(states, open(f"{a.work}/states.json", "w"))
    with open(f"{a.work}/rows.jsonl", "w") as f:
        for si, s in enumerate(states):
            for qn, q in spec["questions"].items():
                f.write(json.dumps({"kind": q["type"], "state": render(spec, s), "instructions": q["instructions"],
                                    "options": options(q), "label": 0, "sid": si, "q": qn}) + "\n")
    print(f"{a.n} states x {len(spec['questions'])} questions -> {a.work}/rows.jsonl")


def train_mlp(X, P, hidden, epochs, seed):
    import torch
    torch.manual_seed(seed)
    X = torch.tensor(X, dtype=torch.float32)
    P = torch.tensor(P, dtype=torch.float32)
    net = torch.nn.Sequential(torch.nn.Linear(X.shape[1], hidden), torch.nn.ReLU(), torch.nn.Linear(hidden, hidden),
                              torch.nn.ReLU(), torch.nn.Linear(hidden, P.shape[1]))
    opt = torch.optim.Adam(net.parameters(), lr=3e-3)
    for ep in range(epochs):
        perm = torch.randperm(len(X))
        for i in range(0, len(X), 256):
            b = perm[i:i + 256]
            loss = -(P[b] * torch.log_softmax(net(X[b]), -1)).sum(-1).mean()
            opt.zero_grad()
            loss.backward()
            opt.step()
    return [(m.weight.detach().numpy(), m.bias.detach().numpy()) for m in net if isinstance(m, torch.nn.Linear)]


def forward(layers, X):
    h = np.asarray(X, np.float32)
    for i, (w, b) in enumerate(layers):
        h = h @ w.T + b
        if i < len(layers) - 1:
            h = np.maximum(h, 0)
    e = np.exp(h - h.max(-1, keepdims=True))
    return e / e.sum(-1, keepdims=True)


def c_ident(s):
    return re.sub(r"\W", "_", s).strip("_").lower()


def c_floats(a):
    return ",".join(f"{x:.7g}f" for x in np.asarray(a, np.float32).reshape(-1))


def emit_c(spec, heads, path):
    nm = c_ident(spec["name"])
    NM = nm.upper()
    L = [f"/* sparrow-pico model `{spec['name']}`, generated by training/pico_compile.py. No dependencies.",
         " * Unofficial community project. Not an AWS or Strands product. */", "#pragma once", "#include <math.h>", ""]
    for f in spec["features"]:
        if f["type"] == "enum":
            L.append("typedef enum { " + ", ".join(f"{NM}_{c_ident(f['name']).upper()}_{c_ident(v).upper()}"
                                               for v in f["values"]) + f" }} {nm}_{c_ident(f['name'])}_t;")
    L.append("typedef struct {")
    for f in spec["features"]:
        t = {"number": "float", "bool": "int"}.get(f["type"], f"{nm}_{c_ident(f['name'])}_t")
        L.append(f"    {t} {c_ident(f['name'])};{' /* ' + f.get('unit', '') + ' */' if f.get('unit') else ''}")
    L.append(f"}} {nm}_state;")
    nin = sum(len(f["values"]) if f["type"] == "enum" else 1 for f in spec["features"])
    L += ["", f"#define {NM}_N_IN {nin}", f"static inline void {nm}_features(const {nm}_state *s, float *x) {{",
          "    int i = 0;"]
    for f in spec["features"]:
        c = c_ident(f["name"])
        if f["type"] == "number":
            L.append(f"    x[i++] = (s->{c} - ({float(f['min'])!r}f)) / ({float(f['max'] - f['min'])!r}f);")
        elif f["type"] == "bool":
            L.append(f"    x[i++] = s->{c} ? 1.f : 0.f;")
        else:
            L.append(f"    for (int k = 0; k < {len(f['values'])}; k++) x[i++] = ((int)s->{c} == k) ? 1.f : 0.f;")
    L += ["    (void)i;", "}", "",
          "static inline void sparrow_pico_dense(const float *w, const float *b, const float *x, int n_in, int n_out,",
          "                                      int relu, float *y) {",
          "    for (int o = 0; o < n_out; o++) {", "        float a = b[o];",
          "        for (int i = 0; i < n_in; i++) a += w[o * n_in + i] * x[i];",
          "        y[o] = relu && a < 0 ? 0 : a;", "    }", "}", ""]
    for qn, (q, layers, temp) in heads.items():
        c = f"{nm}_{c_ident(qn)}"
        names = [o[0] for o in options(q)]
        L.append(f"/* {qn}: {q['type']} — {q['instructions']} Options: {', '.join(names)} */")
        for i, (w, b) in enumerate(layers):
            L.append(f"static const float {c}_w{i}[{w.size}] = {{{c_floats(w)}}};")
            L.append(f"static const float {c}_b{i}[{b.size}] = {{{c_floats(b)}}};")
        h = layers[0][0].shape[0]
        k = layers[-1][0].shape[0]
        L += [f"#define {c.upper()}_N {k}",
              f"static inline void {c}(const {nm}_state *s, float *probs) {{",
              f"    float x[{NM}_N_IN], h0[{h}], h1[{h}], m = -1e30f, z = 0;",
              f"    {nm}_features(s, x);",
              f"    sparrow_pico_dense({c}_w0, {c}_b0, x, {NM}_N_IN, {h}, 1, h0);",
              f"    sparrow_pico_dense({c}_w1, {c}_b1, h0, {h}, {h}, 1, h1);",
              f"    sparrow_pico_dense({c}_w2, {c}_b2, h1, {h}, {k}, 0, probs);",
              f"    for (int i = 0; i < {k}; i++) if (probs[i] > m) m = probs[i];",
              f"    for (int i = 0; i < {k}; i++) z += (probs[i] = expf(probs[i] - m));",
              f"    for (int i = 0; i < {k}; i++) probs[i] /= z;", "}"]
        L.append("static const char *const " + f"{c}_options[{k}] = {{" + ", ".join(f'"{n}"' for n in names) + "};")
        L.append("")
    open(path, "w").write("\n".join(L) + "\n")


def cmd_build(a):
    spec = json.load(open(a.spec))
    states = json.load(open(f"{a.work}/states.json"))
    rows = [json.loads(l) for l in open(f"{a.work}/rows.jsonl")]
    tp = {json.loads(l)["i"]: json.loads(l)["probs"] for l in open(a.teacher or f"{a.work}/teacher.jsonl")}
    X = np.array([featurize(spec, s) for s in states], np.float32)
    rng = np.random.RandomState(0)
    idx = rng.permutation(len(states))
    cut = int(len(idx) * 0.8)
    tr, te = idx[:cut], idx[cut:]
    heads, report = {}, {"spec": spec["name"], "states": len(states), "train": int(cut), "test": int(len(te)),
                         "questions": {}}
    for qn, q in spec["questions"].items():
        P = np.zeros((len(states), len(options(q))), np.float32)
        have = np.zeros(len(states), bool)
        for i, r in enumerate(rows):
            if r["q"] == qn and i in tp:
                P[r["sid"]] = tp[i]
                have[r["sid"]] = True
        trq, teq = tr[have[tr]], te[have[te]]
        layers = train_mlp(X[trq], P[trq], a.hidden, a.epochs, 0)
        pr = forward(layers, X[teq])
        agree = float((pr.argmax(1) == P[teq].argmax(1)).mean())
        n_params = sum(w.size + b.size for w, b in layers)
        heads[qn] = (q, layers, 1.0)
        report["questions"][qn] = {"type": q["type"], "teacher_agreement": round(agree, 4),
                                   "mean_abs_prob_diff": round(float(np.abs(pr - P[teq]).mean()), 4),
                                   "params": int(n_params), "bytes_f32": int(n_params * 4)}
    os.makedirs(a.out, exist_ok=True)
    h = os.path.join(a.out, f"sparrow_pico_{c_ident(spec['name'])}.h")
    emit_c(spec, heads, h)
    np.savez(f"{a.work}/heads.npz", **{f"{qn}_{i}_{t}": arr for qn, (_, ls, _) in heads.items()
                                       for i, (w, b) in enumerate(ls) for t, arr in (("w", w), ("b", b))})
    report["header"] = h
    json.dump(report, open(f"{a.work}/report.json", "w"), indent=1)
    print(json.dumps(report, indent=1))


def main():
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("sample")
    s.add_argument("spec")
    s.add_argument("--n", type=int, default=4000)
    s.add_argument("--seed", type=int, default=0)
    s.add_argument("--work", required=True)
    b = sub.add_parser("build")
    b.add_argument("spec")
    b.add_argument("--work", required=True)
    b.add_argument("--teacher")
    b.add_argument("--out", required=True)
    b.add_argument("--hidden", type=int, default=32)
    b.add_argument("--epochs", type=int, default=200)
    a = ap.parse_args()
    {"sample": cmd_sample, "build": cmd_build}[a.cmd](a)


if __name__ == "__main__":
    main()
