"""Benchmark a model on a real ESP32-S3: build c/examples/esp32s3_bench with the model and the
cases embedded, flash it, read the results over USB, and compare every answer with the expected
label and with the numpy runtime on the host.

  python bench/esp32/run.py MODEL.sparrow [--int8] [--cache64k] [--port /dev/cu.usbmodemXXXX]

Writes bench/results/esp32-<model>-<variant>.json.
"""
from __future__ import annotations

import argparse
import glob
import json
import os
import statistics
import subprocess
import sys
import time

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
APP = os.path.join(ROOT, "c", "examples", "esp32s3_bench")
sys.path.insert(0, os.path.join(ROOT, "python"))
sys.path.insert(0, os.path.join(ROOT, "c", "tools"))
from pack import load, pack  # noqa: E402
from sparrow_decider import Decider, _options  # noqa: E402

KIND = {"noul": 0, "choice": 1, "score": 2}
BENCHES = [("robotbench", "bench/robot/robotbench_v0.jsonl", None),
           ("massive_intent", "bench/massive/massive_intent.jsonl", 100)]


def c_str(s: str) -> str:
    out = []
    for b in s.encode("utf-8"):
        c = chr(b)
        if c == "\\":
            out.append("\\\\")
        elif c == '"':
            out.append('\\"')
        elif 32 <= b < 127:
            out.append(c)
        else:
            out.append(f"\\{b:03o}")
    return '"' + "".join(out) + '"'


def load_cases():
    cases = []
    for name, path, limit in BENCHES:
        rows = [json.loads(l) for l in open(os.path.join(ROOT, path))][:limit]
        for r in rows:
            kind, opts = _options(r["question"])
            if kind == "choice":
                exp = [o[0] for o in opts].index(r["expected"])
            elif kind == "noul":
                exp = int(bool(r["expected"]))
            else:
                exp = int(r["expected"])
            cases.append({"bench": name, "id": r["id"], "state": r["state"], "question": r["question"],
                          "kind": kind, "opts": opts, "expected": exp})
    return cases


def write_cases_h(cases, path):
    L = ["/* generated by bench/esp32/run.py */", "#pragma once", '#include "sparrow.h"',
         "typedef struct { int kind; const char *state; const char *question; int n;"
         " sparrow_option opts[SPARROW_MAX_OPTIONS]; int expected; } bench_case;",
         f"#define N_CASES {len(cases)}", "static const bench_case CASES[N_CASES] = {"]
    for c in cases:
        st = c["state"] if isinstance(c["state"], str) else json.dumps(c["state"], indent=2)
        opts = ", ".join("{" + c_str(n) + ", " + c_str(d or "") + "}" for n, d in c["opts"])
        L.append(f"  {{{KIND[c['kind']]}, {c_str(st.strip())}, {c_str(c['question']['instructions'])}, "
                 f"{len(c['opts'])}, {{{opts}}}, {c['expected']}}},")
    L.append("};")
    open(path, "w").write("\n".join(L) + "\n")


def idf(args, env):
    return idf_in(APP, args, env)


def idf_in(app, args, env):
    cmd = [os.path.join(ROOT, "c", "tools", "idf.sh"), "-C", app] + args
    r = subprocess.run(cmd, env=env, capture_output=True, text=True)
    if r.returncode:
        sys.stderr.write(r.stdout[-4000:] + r.stderr[-4000:])
        raise SystemExit(f"idf.py {' '.join(args)} failed")
    return r.stdout


def esptool(args, env, cwd=None):
    r = subprocess.run(["sh", "-c", ". \"${IDF_PATH:-$HOME/esp/esp-idf}/export.sh\" >/dev/null 2>&1 && esptool.py " + args],
                       env=env, capture_output=True, text=True, cwd=cwd)
    if r.returncode:
        sys.stderr.write(r.stdout[-3000:] + r.stderr[-3000:])
        raise SystemExit("esptool failed: " + args)


def read_serial(port, timeout=600, end="SPARROW_END"):
    """Read until SPARROW_END. The port is opened with DTR and RTS released: on the ESP32-S3's
    built-in USB they drive BOOT and EN, and asserting them would reset the chip into download mode."""
    import serial

    def opn():
        s = serial.Serial()
        s.port, s.baudrate, s.timeout = port, 115200, 0.5
        s.dtr = s.rts = False
        s.open()
        return s

    s, lines, buf, t0 = None, [], b"", time.time()
    while time.time() - t0 < timeout:
        try:
            if s is None:
                s = opn()
            buf += s.read(4096)
        except (serial.SerialException, OSError):  # the USB port re-enumerates across resets
            s = None
            time.sleep(0.3)
            continue
        while b"\n" in buf:
            line, buf = buf.split(b"\n", 1)
            line = line.decode("utf-8", "replace").strip()
            lines.append(line)
            if line.startswith(end):
                return lines
    raise SystemExit(f"timed out waiting for {end}; got:\n" + "\n".join(lines[-20:]))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("model")
    ap.add_argument("--int8", action="store_true")
    ap.add_argument("--cache64k", action="store_true")
    ap.add_argument("--port")
    ap.add_argument("--tag", help="suffix for the variant name, e.g. batched")
    ap.add_argument("--profile", action="store_true", help="per-stage cycle counts")
    ap.add_argument("--psram", action="store_true", help="copy the model blob from flash to PSRAM at boot")
    ap.add_argument("--mlp-internal", action="store_true", help="move the MLP weights into internal RAM")
    ap.add_argument("--balance", action="store_true", help="pack with per-block gains (one int8 scale per row)")
    ap.add_argument("--no-flash", action="store_true", help="only reset and read (reuse the last flash)")
    a = ap.parse_args()
    port = a.port or sorted(glob.glob("/dev/cu.usbmodem*") + glob.glob("/dev/ttyACM*"))[0]
    variant = ("profile-" if a.profile else "") + ("int8" if a.int8 else "float") + ("-cache64k" if a.cache64k else "") + ("-psram" if a.psram else "") + ("-mlpint" if a.mlp_internal else "") + ("-balanced" if a.balance else "") + (f"-{a.tag}" if a.tag else "")
    d = Decider.load(a.model)
    cases = load_cases()
    main_dir = os.path.join(APP, "main")
    write_cases_h(cases, os.path.join(main_dir, "cases.h"))
    gains = None
    if a.balance:
        from pack import block_gains
        gains = block_gains(a.model, [(c["state"], c["question"]) for c in cases])
    open(os.path.join(main_dir, "model.spb"), "wb").write(pack(*load(a.model), gains=gains))
    env = dict(os.environ)
    env["PATH"] = "/opt/homebrew/opt/python@3.12/libexec/bin:" + env["PATH"]
    build = os.path.join(APP, f"build-{variant}")
    defaults = "sdkconfig.defaults" + (";sdkconfig.cache64k" if a.cache64k else "")
    args = ["-B", build, "-D", f"SDKCONFIG={build}/sdkconfig", "-D", f"SDKCONFIG_DEFAULTS={defaults}",
            "-D", f"SPARROW_INT8={1 if a.int8 else 0}", "-D", f"SPARROW_PROFILE={1 if a.profile else 0}", "-D", f"SPARROW_BLOB_PSRAM={1 if a.psram else 0}", "-D", f"SPARROW_MLP_INTERNAL={1 if a.mlp_internal else 0}", "-D", f"SPARROW_HIDDEN={max(128, int(d.cfg.get('hidden', 256)))}", "-D", f"SPARROW_WIDE={1 if d.cfg.get('dim', 128) > 128 or 'micro' in d.name else 0}"]
    # watchdog reset: a plain EN reset over the built-in USB can leave the S3 in download mode
    if a.no_flash:
        esptool(f"-p {port} --after watchdog_reset read_mac", env)
    else:
        t = time.time()
        idf(args + ["build"], env)
        print(f"built {variant} in {time.time() - t:.0f}s", flush=True)
        esptool(f"--chip esp32s3 -p {port} -b 921600 --after watchdog_reset write_flash @flash_args", env, cwd=build)
        print("flashed", flush=True)
    lines = read_serial(port)
    head = next(l for l in lines if l.startswith("SPARROW_BEGIN"))
    meta = dict(kv.split("=") for kv in head.split()[1:])
    res = [l.split() for l in lines if l.startswith("C ")]
    pico = dict(kv.split("=") for kv in next(l for l in lines if l.startswith("PICO")).split()[1:])
    end = dict(kv.split("=") for kv in next(l for l in lines if l.startswith("SPARROW_END")).split()[1:])
    prof = next((dict(kv.split("=") for kv in l.split()[1:]) for l in lines if l.startswith("PROF")), None)
    by, us_by, agree, diffs = {}, {}, 0, []
    for f in res:
        i, pred, exp, us = int(f[1]), int(f[2]), int(f[3]), int(f[4])
        c = cases[i]
        p_dev = np.array([float(x) for x in f[6:]])
        _, _, _, p_host = d.probs(c["state"], c["question"])
        diffs.append(float(np.abs(p_dev - p_host).max()))
        host_pred = int(p_host.argmax()) if c["kind"] != "score" else int((np.arange(len(p_host)) * p_host).sum() + 0.5)
        agree += int(host_pred == pred)
        b = by.setdefault(c["bench"], [0, 0])
        b[0] += int(pred == exp)
        b[1] += 1
        us_by.setdefault(c["bench"], []).append(us)
    allus = sorted(u for v in us_by.values() for u in v)

    def stats(v):
        v = sorted(v)
        return {"p50_ms": round(statistics.median(v) / 1000, 2), "p95_ms": round(v[int(0.95 * (len(v) - 1))] / 1000, 2),
                "mean_ms": round(sum(v) / len(v) / 1000, 2), "max_ms": round(v[-1] / 1000, 2)}

    rep = {"model": d.name, "bench": "esp32s3", "variant": variant, "board": "ESP32-S3 QFN56 rev0.2, 16MB flash, 8MB PSRAM",
           "cpu_mhz": int(meta["cpu_mhz"]), "blob_bytes": int(meta["blob"]), "ctx_bytes": int(meta["ctx"]),
           "load_us": int(meta["load_us"]), "cases": len(res),
           "accuracy": {k: f"{v[0]}/{v[1]}" for k, v in by.items()},
           "agree_with_host": f"{agree}/{len(res)}", "max_prob_diff_vs_host": round(max(diffs), 5),
           "latency": {"all": stats(allus), **{k: stats(v) for k, v in us_by.items()}},
           "pico_rover_action_us": float(pico["us_per_call"]), "pico_cycles": int(pico["cycles_per_call"]),
           "profile_ms_total": ({k: round(int(v) / (int(meta["cpu_mhz"]) * 1000), 1) for k, v in prof.items()} if prof else None),
           "heap_free": int(end["heap_free"]), "heap_min": int(end["heap_min"]), "stack_hwm_words": int(end["stack_hwm"])}
    out = os.path.join(ROOT, "bench", "results", f"esp32-{d.name}-{variant}.json")
    json.dump(rep, open(out, "w"), indent=1)
    print(json.dumps(rep, indent=1))


if __name__ == "__main__":
    main()
