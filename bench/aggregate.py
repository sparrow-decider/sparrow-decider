"""Collect bench/results/*.json into bench/RESULTS.md (one table per benchmark)."""
import glob
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))


def main():
    robot, jev, cpar, massive = [], [], [], {}
    for p in sorted(glob.glob(os.path.join(HERE, "results", "*.json"))):
        r = json.load(open(p))
        if r.get("bench", "").startswith("robotbench"):
            robot.append(r)
        elif r.get("bench", "").startswith("massive"):
            massive.setdefault(r["model"], {})[r["bench"].split(".")[0]] = r
        elif "jevbench" in r:
            jev.append(r)
        elif r.get("bench") == "c-parity":
            cpar.append(r)
    out = ["# Benchmark results", "", "Generated by `bench/aggregate.py` from `bench/results/`. Local runs, not board scores.", ""]
    out += ["## RobotBench v0 (55 hand-written robot decisions)", "",
            "| Model | Right | Acc | skill | nav | check | recover | urgency | Time / question |", "|---|---|---|---|---|---|---|---|---|"]
    for r in sorted(robot, key=lambda r: -r["acc"]):
        f = r["per_family"]
        t = f"{r['p50_ms']} ms (1 CPU core)" if "p50_ms" in r else f"{r['sec_per_q'] * 1000:.0f} ms ({r['device']}, batched)"
        out.append(f"| {r['model']} | {r['right']}/{r['n']} | {r['acc']:.3f} | {f['skill']} | {f['nav']} | {f['check']} | "
                   f"{f['recover']} | {f['urgency']} | {t} |")
    out += ["", "## MASSIVE routing (Amazon MASSIVE 1.1 en-US test, 600 utterances, held out of training)", "",
            "| Model | Domain (18 options) | Intent within domain | Time / question |", "|---|---|---|---|"]
    for m, d in sorted(massive.items(), key=lambda kv: -sum(x["acc"] for x in kv[1].values())):
        dm, it = d.get("massive_domain", {}), d.get("massive_intent", {})
        t = dm.get("p50_ms")
        t = f"{t} ms (1 CPU core)" if t is not None else f"{dm.get('sec_per_q', 0) * 1000:.0f} ms ({dm.get('device')}, batched)"
        out.append(f"| {m} | {dm.get('acc', '-')} | {it.get('acc', '-')} | {t} |")
    out += ["", "## JevBench public (231 tasks, local v1.5 proxy)", "",
            "| Model | File | Right | Intelligence | noul | choice | score | p50 / p95 | Peak RSS |", "|---|---|---|---|---|---|---|---|---|"]
    for r in sorted(jev, key=lambda r: -r["jevbench"]["right"]):
        j, k, lat = r["jevbench"], r["jevbench"]["per_kind"], r["latency_ms"]
        out.append(f"| {r['model']} | {r['file_mb']} MB | {j['right']}/{j['n']} | {j['intelligence']} | {k.get('noul')} | "
                   f"{k.get('choice')} | {k.get('score')} | {lat['p50']} / {lat['p95']} ms | {r['peak_rss_mb']} MB |")
    out += ["", "## C runtime (host, 1 core): parity with numpy and speed", "",
            "| Model | SPB1 blob | Cases | Argmax agree | Max prob diff | C time / question (p50) | Flags |",
            "|---|---|---|---|---|---|---|"]
    for r in sorted(cpar, key=lambda r: r["blob_mb"]):
        out.append(f"| {r['model']} | {r['blob_mb']} MB | {r['cases']} | {r['argmax_agree']} | {r['max_abs_diff']} | "
                   f"{r['c_us_p50']} us | `{r.get('cflags', '')}` |")
    open(os.path.join(HERE, "RESULTS.md"), "w").write("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
